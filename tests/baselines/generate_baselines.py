#!/usr/bin/env python
"""Regenerate characterization baselines in tests/baselines/.

Run once per venv against pre-change code:

    # pybamm-only baselines (gate: .venv, CPython 3.14)
    .venv/bin/python tests/baselines/generate_baselines.py

    # pybop-dependent baselines (gate: .venv-ecosystem312)
    .venv-ecosystem312/bin/python tests/baselines/generate_baselines.py

The script refuses to overwrite the current source: it snapshots whatever code
is currently imported, so run it BEFORE applying changes to regenerate, never
after. Baselines encode the pre-audit scientific behaviour; regeneration from
modified code defeats the purpose of the gate.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
BASE_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(REPO_ROOT / "tests" / "characterization"))
sys.path.insert(0, str(REPO_ROOT))

import numpy as np  # noqa: E402

from _charconfig import CHAR_BASELINE_DICT, CHAR_P2_MULTI, CHAR_P2_SINGLE  # noqa: E402

GENERATED_NOTE = {
    "_meta": "Generated by tests/baselines/generate_baselines.py from pre-audit code.",
}


def gen_p0(workspace: Path) -> None:
    from pybamm_closed_loop.pybamm_engine import BaselineRunConfig, run, save_result

    config = BaselineRunConfig.model_validate(CHAR_BASELINE_DICT)
    result = run(config)

    out_dir = workspace / "inprocess"
    save_result(result, out_dir)
    npz = np.load(out_dir / "solution_arrays.npz")
    dest = BASE_DIR / "char_baseline_120s.npz"
    np.savez_compressed(dest, **{k: npz[k] for k in npz.files})

    manifest = result.manifest
    scientific = {
        **GENERATED_NOTE,
        "solution_summary": manifest["solution_summary"],
        "extraction": manifest["extraction"],
    }
    (BASE_DIR / "char_baseline_manifest.json").write_text(
        json.dumps(scientific, indent=2), encoding="utf-8"
    )
    print("wrote", dest, "and", BASE_DIR / "char_baseline_manifest.json")


def gen_p0_cli(workspace: Path) -> None:
    import yaml

    from pybamm_closed_loop.pybamm_engine import BaselineRunConfig

    config = BaselineRunConfig.model_validate(CHAR_BASELINE_DICT)
    cfg_path = workspace / "char_baseline_120s.yaml"
    cfg_path.write_text(yaml.safe_dump(config.model_dump()), encoding="utf-8")

    out_dir = workspace / "cli"
    proc = subprocess.run(
        [
            sys.executable,
            str(REPO_ROOT / "scripts" / "run_baseline.py"),
            "--config",
            str(cfg_path),
            "--out",
            str(out_dir),
        ],
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"CLI baseline failed:\n{proc.stdout}\n{proc.stderr}")
    dest = BASE_DIR / "char_baseline_cli.npz"
    npz = np.load(out_dir / "solution_arrays.npz")
    np.savez_compressed(dest, **{k: npz[k] for k in npz.files})
    print("wrote", dest)


def gen_p2(workspace: Path, raw: dict, tag: str) -> None:
    import yaml

    import benchmarks.parameter_recovery.run_recovery_benchmark as bench

    cfg_path = workspace / f"{raw['run_id']}.yaml"
    cfg_path.write_text(yaml.safe_dump(raw), encoding="utf-8")
    out_dir = workspace / "out"
    argv = [
        "prog",
        "--config",
        str(cfg_path),
        "--out",
        str(out_dir),
    ]
    old_argv = sys.argv
    sys.argv = argv
    try:
        bench.main()
    finally:
        sys.argv = old_argv
    lines = (out_dir / raw["run_id"] / "summary.md").read_text()
    print(lines)
    report = json.loads((out_dir / raw["run_id"] / "report.json").read_text())
    bundle = {
        **GENERATED_NOTE,
        "runs": report["runs"],
        "best_run_index": report["best_run_index"],
        "generated_data": report["generated_data"],
        "build_info": report["build_info"],
    }
    dest = BASE_DIR / f"char_recovery_{tag}.json"
    dest.write_text(json.dumps(bundle, indent=2), encoding="utf-8")
    print("wrote", dest)


def gen_p3() -> None:
    from pybamm_closed_loop.eval.benchmark import load_items, run_benchmark
    from pybamm_closed_loop.literature.ingest import DocumentStore

    data_root = REPO_ROOT / "data"
    items = load_items(data_root / "eval" / "extraction_benchmark_v1.jsonl")
    store = DocumentStore(data_root / "literature_store")
    report = run_benchmark(items, store, client=None)
    report["_meta"] = GENERATED_NOTE["_meta"]
    dest = BASE_DIR / "char_p3_offline.json"
    dest.write_text(json.dumps(report, indent=2), encoding="utf-8")
    print("wrote", dest, "metrics:", report["metrics"])


def main() -> int:
    has_pybop = None
    try:
        import pybop  # noqa: F401

        has_pybop = True
    except ImportError:
        has_pybop = False
    import pybamm  # noqa: F401

    with tempfile.TemporaryDirectory(prefix="char-baseline-") as tmp:
        workspace = Path(tmp)
        gen_p0(workspace)
        gen_p0_cli(workspace)
        if has_pybop:
            gen_p2(workspace, CHAR_P2_SINGLE, "single")
            gen_p2(workspace, CHAR_P2_MULTI, "multi")
            gen_p3()
        else:
            print(
                "pybop not installed in this venv; only pybamm-only baselines "
                "were generated. Run the pybop-dependent part under "
                ".venv-ecosystem312."
            )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
